/**
 * Модель контента.
 *
 * Каждый вопрос — самодостаточный объект. Чтобы добавить вопрос,
 * достаточно дописать объект в файл нужного режима (src/data/questions/*.ts).
 * Проверка корректности: `npm run check`.
 */

export type QuestionType =
  | 'retell' // книга по дурацкому пересказу (плохой / AI / корпоративный / Netflix…)
  | 'line' // книга по одной фразе
  | 'character' // персонаж по подсказкам
  | 'author' // автор по подсказкам (+ опционально портрет)
  | 'emoji' // «обложка» из эмодзи
  | 'fake' // какой книги не существует
  | 'screen' // книга или кино
  | 'fame' // хит сразу или признание позже
  | 'money'; // деньги и литература

/** 1 — лёгкий, 2 — средний, 3 — сложный */
export type Difficulty = 1 | 2 | 3;

export interface Question {
  /** Уникальный id. Никогда не меняйте id уже опубликованного вопроса — на нём держится «игра дня». */
  id: string;
  type: QuestionType;
  difficulty: Difficulty;
  /** Основной текст: пересказ, фраза, первая подсказка, описание и т. п. */
  prompt: string;
  /** Короткая плашка над текстом, например стиль пересказа: «Netflix», «Вакансия». */
  tag?: string;
  /** Дополнительные подсказки, открываются по одной (для character / author). */
  clues?: string[];
  /** Крупная «обложка» из эмодзи (для emoji). */
  emoji?: string;
  /** Путь к локальной картинке относительно /public, например "portraits/tolstoy.jpg". */
  image?: string;
  /** Переопределяет общий вопрос режима («Какая это книга?»). */
  ask?: string;
  /** Варианты ответа. Порядок перемешивается, если не задан fixedOrder. */
  options: string[];
  /** Правильный ответ — строка, в точности совпадающая с одним из options. */
  answer: string;
  /** Показывается после ответа: короткий факт или разбор. */
  explanation: string;
  /** Связанная книга (для статистики и будущих фильтров). */
  book?: string;
  /** Связанный автор. */
  author?: string;
  /** Не перемешивать варианты (для бинарных вопросов «книга / кино»). */
  fixedOrder?: boolean;
}
